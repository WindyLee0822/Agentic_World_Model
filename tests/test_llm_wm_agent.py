"""The ``llm_wm`` solver: an LLM tool-calling agent that interacts with the world model.

These tests use an injected, deterministic ``decide``/``complete`` (no API access) to verify the
harness wiring: for B0/B1/Ours the agent's trajectory is generated by stepping against the
read-grounded world model (not the real env), the real env is never written during sampling, and
exactly one trajectory is committed.
"""

from __future__ import annotations

import pytest

from tts.agents import LLMAgent
from tts.config import Config, SolverConfig
from tts.harness import run_decision
from tts.llm.solver_agent import parse_action
from tts.types import Action
from conftest import make_feasible_infeasible_env, SELECT


def _gold_decider(env):
    """A stand-in 'LLM' policy: select the (gold) feasible item once, then finish."""

    def decide(view, history):
        if len(history) == 0:
            return Action(SELECT, {"item_id": env._gold_item})
        return None

    return decide


@pytest.mark.parametrize("method", ["b0", "b1", "ours"])
def test_llm_wm_agent_interacts_with_world_model(method):
    env = make_feasible_infeasible_env()
    pre = env.state_hash()
    agent = LLMAgent(_gold_decider(env), max_steps=4)
    cfg = Config(method=method, env="fake", N=3, seed=1, solver=SolverConfig(agent="llm_wm"))

    out = run_decision(env, cfg, agent=agent)

    # the sampling phase interacts with the WM, never the real env, and commits exactly once
    assert out.record.simulator_writes == 0
    assert out.record.n_commits == 1
    assert env.state_hash() != pre  # the single commit mutated real state
    assert out.record.success  # the gold (feasible) item was selected and committed


def test_llm_wm_b0_steps_against_world_model_not_noop():
    """B0 in llm_wm mode must drive the agent against the WM stepper (observation 'ok'), not NoOp."""
    env = make_feasible_infeasible_env()
    agent = LLMAgent(_gold_decider(env), max_steps=4)
    cfg = Config(method="b0", env="fake", N=1, seed=0, solver=SolverConfig(agent="llm_wm"))

    out = run_decision(env, cfg, agent=agent)

    obs = out.rollouts[0].trajectory.steps[0].observation
    assert obs is not None and obs.content == "ok"  # served by the WM (NoOp would be "")


def test_make_llm_solver_agent_uses_injected_complete():
    """The factory wires an injected chat backend and parses its CALL/FINISH replies."""
    from tts.llm.solver_agent import make_llm_solver_agent

    env = make_feasible_infeasible_env()
    replies = iter([f"CALL {SELECT} {{\"item_id\": \"{env._gold_item}\"}}", "FINISH"])
    agent = make_llm_solver_agent(complete_fn=lambda messages: next(replies))
    cfg = Config(method="ours", env="fake", N=1, seed=0, solver=SolverConfig(agent="llm_wm"))

    out = run_decision(env, cfg, agent=agent)

    assert out.record.n_commits == 1
    assert out.record.success


def test_parse_action_handles_call_and_finish():
    a = parse_action('CALL book_reservation {"id": "r1", "n": 2}')
    assert a is not None and a.name == "book_reservation" and a.args == {"id": "r1", "n": 2}
    assert parse_action("FINISH") is None
    assert parse_action("CALL select_item") is not None  # missing args -> {}


# --------------------------------------------------------------------------- #
# The faithful llm_wm harness path: env.run_agent_rollout_wm -> select -> commit
# --------------------------------------------------------------------------- #

from tts.trajectory import RewardInfo, Step, Trajectory  # noqa: E402
from tts.types import Action  # noqa: E402
from conftest import FakeTaskEnv  # noqa: E402


class _FakeWMEnv(FakeTaskEnv):
    """A Fake env that stands in for the official-agent-against-WM rollout.

    ``run_agent_rollout_wm`` returns a canned (trajectory, WM-predicted reward) per seed — odd seeds
    'fail' (select an infeasible item, predicted False), even seeds 'succeed' (select gold, predicted
    True) — so the selector must pick a predicted-success rollout, and the harness must commit it
    exactly once without writing during sampling."""

    def __init__(self):
        super().__init__({"A": [1.0, 1.0, 1.0], "B": [9.0, 9.0]}, cap=5.0)
        self.wm_rollouts = 0

    def run_agent_rollout_wm(self, config, method, seed, budget, cache=None):
        self.wm_rollouts += 1
        good = (seed % 2 == 0)
        item = self._gold_item if good else "B"
        traj = Trajectory(steps=[Step(Action(SELECT, {"item_id": item}))])
        traj.sim_messages = None  # exercise the assistant-only commit path
        predicted = RewardInfo(reward=1.0 if good else 0.0, success=good, grounded=False)
        return traj, predicted, None


@pytest.mark.parametrize("method", ["b0", "b1", "ours"])
def test_faithful_llm_wm_path_selects_and_commits(method):
    env = _FakeWMEnv()
    pre = env.state_hash()
    cfg = Config(method=method, env="fake", N=4, seed=2, solver=SolverConfig(agent="llm_wm"))

    out = run_decision(env, cfg)  # agent is None -> faithful WM-agent path

    assert env.wm_rollouts == (1 if method == "b0" else 4)  # N rollouts against the WM
    assert out.record.simulator_writes == 0  # sampling never wrote the real env
    assert out.record.n_commits == 1  # exactly one commit
    assert env.state_hash() != pre  # the single commit mutated real state
    if method != "b0":
        # a predicted-success rollout exists in the pool (even seeds) and must be selected
        assert out.rollouts[out.selected_index].predicted.success
        assert out.record.success


