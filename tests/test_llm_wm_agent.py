# --------------------------------------------------------------------------- #
# The faithful llm_wm harness path: env.run_agent_rollout_wm -> select -> commit
# --------------------------------------------------------------------------- #

from tts.trajectory import RewardInfo, Step, Trajectory  # noqa: E402
from tts.types import Action  # noqa: E402
from conftest import FakeTaskEnv  # noqa: E402


class _FakeWMEnv(FakeTaskEnv):
    """A Fake env that stands in for the official-agent-against-WM rollout.

    ``run_agent_rollout_wm`` returns a canned (trajectory, WM-predicted reward) per seed — odd seeds
    'fail' (select an infeasible item, predicted False), even seeds 'succeed' (select gold, predicted
    True) — so the selector must pick a predicted-success rollout, and the harness must commit it
    exactly once without writing during sampling."""

    def __init__(self):
        super().__init__({"A": [1.0, 1.0, 1.0], "B": [9.0, 9.0]}, cap=5.0)
        self.wm_rollouts = 0

    def run_agent_rollout_wm(self, config, method, seed, budget, cache=None):
        self.wm_rollouts += 1
        good = (seed % 2 == 0)
        item = self._gold_item if good else "B"
        traj = Trajectory(steps=[Step(Action(SELECT, {"item_id": item}))])
        traj.sim_messages = None  # exercise the assistant-only commit path
        predicted = RewardInfo(reward=1.0 if good else 0.0, success=good, grounded=False)
        return traj, predicted, None


class _RetryingWMEnv(_FakeWMEnv):
    def __init__(self):
        super().__init__()
        self.attempts = {}

    def run_agent_rollout_wm(self, config, method, seed, budget, cache=None):
        self.attempts[seed] = self.attempts.get(seed, 0) + 1
        if self.attempts[seed] == 1:
            raise RuntimeError("transient rollout failure")
        return super().run_agent_rollout_wm(config, method, seed, budget, cache)


class _PartiallyFailingWMEnv(_FakeWMEnv):
    def run_agent_rollout_wm(self, config, method, seed, budget, cache=None):
        if seed == 3:
            self.wm_rollouts += 1
            raise RuntimeError("permanent rollout failure")
        return super().run_agent_rollout_wm(config, method, seed, budget, cache)


class _AlwaysFailingWMEnv(_FakeWMEnv):
    def run_agent_rollout_wm(self, config, method, seed, budget, cache=None):
        self.wm_rollouts += 1
        raise RuntimeError("permanent rollout failure")


class _TelemetryWMEnv(_FakeWMEnv):
    def run_agent_rollout_wm(self, config, method, seed, budget, cache=None):
        traj, predicted, root = super().run_agent_rollout_wm(
            config, method, seed, budget, cache)
        predicted.metadata = {
            "python_calls": seed,
            "python_failures": seed % 2,
            "python_forced": seed + 1,
            "python_mode_misses": seed % 2,
        }
        return traj, predicted, root


class _RefiningWMEnv(_FakeWMEnv):
    def __init__(self):
        super().__init__()
        self.refine_calls = 0

    def refine_rollout_scores(self, config, rollouts):
        self.refine_calls += 1
        if len(rollouts) >= 4:
            rollouts[2].predicted.reward = 2.0


@pytest.mark.parametrize("method", ["b0", "b1", "ours"])
def test_faithful_llm_wm_path_selects_and_commits(method):
    env = _FakeWMEnv()
    pre = env.state_hash()
    cfg = Config(method=method, env="fake", N=4, seed=2, solver=SolverConfig(agent="llm_wm"))

    out = run_decision(env, cfg)  # agent is None -> faithful WM-agent path

    assert env.wm_rollouts == (1 if method == "b0" else 4)  # N rollouts against the WM
    assert out.record.simulator_writes == 0  # sampling never wrote the real env
    assert out.record.n_commits == 1  # exactly one commit
    assert env.state_hash() != pre  # the single commit mutated real state
    if method != "b0":
        # a predicted-success rollout exists in the pool (even seeds) and must be selected
        assert out.rollouts[out.selected_index].predicted.success
        assert out.record.success


