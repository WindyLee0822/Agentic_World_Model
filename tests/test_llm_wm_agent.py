# Dirty-read routing: a read of a written entity is PREDICTED (force_predict), not served exact
# --------------------------------------------------------------------------- #

from tts.budget import Budget  # noqa: E402
from tts.cache import ReadCache  # noqa: E402
from tts.config import BudgetConfig, SimulatorConfig  # noqa: E402
from tts.worldmodel import ReadGroundedWorldModel  # noqa: E402
from tts.abcs import EntityStore, ShadowEvaluator  # noqa: E402
from tts.trajectory import RewardInfo as _RI  # noqa: E402


class _NullStore(EntityStore):
    def read(self, t, i):
        return None

    def list_ids(self, t):
        return []


class _RecordingAgenticEval(ShadowEvaluator):
    """Minimal agentic evaluator that records the ``force_predict`` flag per observe call."""

    agentic = True

    def __init__(self):
        self.calls = []

    def seed_entities(self, actions):
        return []

    def child_references(self, t, i, row):
        return []

    def reward_from_shadow(self, shadow, actions):
        return _RI()

    def observe_agentic(self, reader, action, force_predict=False):
        self.calls.append((action.name, force_predict))
        return (f"served:{action.name}", False)

    def reward_agentic(self, reader, actions):
        return _RI(reward=1.0, success=True)


def test_predict_step_forces_prediction_vs_step():
    ev = _RecordingAgenticEval()
    wm = ReadGroundedWorldModel(_NullStore(), ev, SimulatorConfig(kind="recursive"),
                                Budget(), BudgetConfig(), ReadCache())
    wm.step(Action("get_reservation_details", {"id": "r1"}))       # normal -> may serve exact
    wm.predict_step(Action("get_reservation_details", {"id": "r1"}))  # dirty -> must force predict
    assert ev.calls == [("get_reservation_details", False), ("get_reservation_details", True)]


def test_sandbox_preamble_opt_in(monkeypatch):
    from tts.env.appworld_react_agent import _maybe_add_sandbox_preamble, _SANDBOX_PREAMBLE

    base = [{"role": "system", "content": "OFFICIAL"}, {"role": "user", "content": "task"}]

    monkeypatch.delenv("TTS_APPWORLD_SANDBOX_PROMPT", raising=False)
    off = _maybe_add_sandbox_preamble([dict(m) for m in base])
    assert off[0]["content"] == "OFFICIAL"

    monkeypatch.setenv("TTS_APPWORLD_SANDBOX_PROMPT", "1")
    on = _maybe_add_sandbox_preamble([dict(m) for m in base])
    assert on[0]["content"].startswith(_SANDBOX_PREAMBLE)
    assert "OFFICIAL" in on[0]["content"]
    assert on[1]["content"] == "task"  # other messages untouched

    # inserts a system message when none exists
    inserted = _maybe_add_sandbox_preamble([{"role": "user", "content": "x"}])
    assert inserted[0]["role"] == "system" and inserted[1]["content"] == "x"
