"""An LLM tool-calling **solver** that interacts with a stepper (e.g. the world model).

This is a lightweight ReAct-style agent: given the task instruction + tool schema and the running
observation history, it asks an LLM for the single next tool call (or to finish).  It is the agent
used by the ``llm_wm`` solver mode, where the harness drives it against the read-grounded
:class:`~tts.abcs.WorldModel` (the *simulated* env) while sampling — so each candidate trajectory is
generated by interacting with the world model, and only the selected one is committed to the real
environment.

Contrast with the **official-prompt agent** (``--agent llm``): that one is run by the env's
``run_agent_rollout`` against the *real* env (reproducing the official benchmark), and the world
model only *scores* the finished trajectory afterwards.  Here the agent instead *interacts* with the
world model step-by-step.

Decoupling is preserved: :class:`~tts.agents.LLMAgent` stays LLM-free (it only holds an injected
``decide`` callable); the concrete LLM dependency lives here, behind a factory.  The ``complete``
callable is injectable so tests can drive the agent deterministically without any API access.
"""

from __future__ import annotations

import json
from typing import Callable, Dict, List, Optional

from ..agents import LLMAgent
from ..trajectory import Trajectory
from ..types import Action


def _format_tools(tool_names: List[str], tool_docs: Dict[str, str]) -> str:
    lines: List[str] = []
    for n in tool_names:
        doc = (tool_docs or {}).get(n, "")
        lines.append(f"- {n}: {doc}" if doc else f"- {n}")
    return "\n".join(lines) or "(no tools)"


def _format_history(history: Trajectory) -> str:
    out: List[str] = []
    for s in history.steps:
        obs = s.observation.content if s.observation else ""
        err = " [ERROR]" if (s.observation and s.observation.error) else ""
        args = json.dumps(s.action.args or {}, sort_keys=True, default=str)
        out.append(f"CALL {s.action.name} {args} ->{err} {obs}")
    return "\n".join(out) or "(no actions yet)"


def parse_action(text: str) -> Optional[Action]:
    """Parse one ``CALL <tool> {json}`` line into an :class:`Action` (``None`` on ``FINISH``)."""
    up = (text or "").upper()
    for line in (text or "").splitlines():
        s = line.strip()
        if s.upper().startswith("CALL "):
            rest = s[5:].strip()
            name = rest.split()[0] if rest else ""
            args: Dict = {}
            br = rest.find("{")
            if br != -1:
                try:
                    args = json.loads(rest[br:])
                except Exception:
                    args = {}
            if name:
                return Action(name, args)
    if "FINISH" in up:
        return None
    return None


def _tool_docs_of(view) -> Dict[str, str]:
    getter = getattr(view, "tool_docs", None)
    if callable(getter):
        try:
            return getter() or {}
        except Exception:
            return {}
    return {}


def make_llm_solver_agent(
    model: Optional[str] = None,
    temperature: float = 0.0,
    max_steps: int = 30,
    complete_fn: Optional[Callable[[list], str]] = None,
) -> LLMAgent:
    """Build an :class:`~tts.agents.LLMAgent` that proposes the next tool call from observations.

    ``complete_fn(messages) -> str`` is the chat backend; when omitted, the project's
    :class:`~tts.llm.chat_client.ChatClient` is built lazily (Azure-AAD aware).  Injecting it keeps
    the agent fully testable offline.
    """
    state: Dict[str, object] = {"complete": complete_fn}

    def _complete(messages: list) -> str:
        fn = state["complete"]
        if fn is None:
            from . import make_chat_client

            try:
                from .azure import azure_deployment

                default = azure_deployment()
            except Exception:
                default = None
            client = make_chat_client(model=model or default)
            fn = lambda msgs: client.complete(msgs, temperature=temperature, max_tokens=300)  # noqa: E731
            state["complete"] = fn
        return fn(messages)

    def decide(view, history: Trajectory) -> Optional[Action]:
        tool_names = list(view.tool_schema())
        prompt = (
            "You are an agent solving a customer-service task by calling tools against a live "
            "system. Work step by step: inspect state with read tools before making changes.\n\n"
            f"TASK:\n{view.instruction()}\n\n"
            f"AVAILABLE TOOLS:\n{_format_tools(tool_names, _tool_docs_of(view))}\n\n"
            f"ACTIONS SO FAR (with their results):\n{_format_history(history)}\n\n"
            "Decide the SINGLE next step. Reply with exactly one line:\n"
            "  CALL <tool_name> {json args}   to call a tool, or\n"
            "  FINISH                          when the task is fully complete.\n"
            "Use only tools from the list above and valid JSON for the args."
        )
        resp = _complete([{"role": "user", "content": prompt}])
        return parse_action(resp)

    return LLMAgent(decide, max_steps=max_steps)


__all__ = ["make_llm_solver_agent", "parse_action"]
